def fetch(latitude, longitude):
    url = f"https://wttr.in/{latitude},{longitude}?format=j1"
    raw = http.get_json(url, timeout=20, retries=2)

    cur = raw["current_condition"][0]
    today = raw["weather"][0]
    code = int(cur.get("weatherCode") or 113)
    desc, icon = WWO.get(code, (cur.get("weatherDesc", [{}])[0].get("value", "—").strip(), ""))

    return {
        "temp": int(cur["temp_C"]),
        "feels_like": int(cur["FeelsLikeC"]),
        "humidity": cur["humidity"],
        "wind": round(int(cur["windspeedKmph"]) / 3.6, 1),
        "weather": desc,
        "icon": icon,
        "high": int(today["maxtempC"]),
        "low": int(today["mintempC"]),
    }
